def test_the_repo_cost_tables_use_the_helper_the_warnings_use(tmp_path):
    """Smoke test on the real layout, with profiles.json: the table rows are scripts/skill_descriptions.py's numbers."""
    root = tmp_path / "copy"
    shutil.copytree(REPO / "plugins", root / "plugins")
    shutil.copytree(REPO / ".claude-plugin", root / ".claude-plugin")
    shutil.copy2(REPO / "profiles.json", root / "profiles.json")
    (root / "scripts").mkdir()
    for script in ("gen-catalog.py", "skill_descriptions.py"):
        shutil.copy2(REPO / "scripts" / script, root / "scripts" / script)
    res = subprocess.run([sys.executable, str(root / "scripts/gen-catalog.py")], capture_output=True, text=True)
    assert res.returncode == 0, res.stderr
    sys.path.insert(0, str(REPO / "scripts"))
    import skill_descriptions as sd
    prof = json.loads((REPO / "profiles.json").read_text(encoding="utf-8"))
    costs = sd.profile_costs(sd.plugin_costs(sd.listing_entries(REPO)), prof["profiles"])
    rows = cost_rows((root / "SKILLS.md").read_text(encoding="utf-8"), "Per profile")[2:]
    for name, c in costs.items():
        row = next(x for x in rows if x.startswith(f"| `{name}` |"))
        assert f"| {c.entries} | {c.chars:,} | {c.names:,} |" in row
    assert rows[-1].startswith("| all plugins |") and f"| {sum(c.chars for c in costs.values()):,} |" in rows[-1]
