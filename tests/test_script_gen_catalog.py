# --- the "Listing cost" section ------------------------------------------------------------------------------

def cost_rows(text: str, heading: str) -> list[str]:
    """The table under `### heading` of the Listing cost section: header, separator and rows."""
    lines = text.splitlines()
    start = lines.index(f"### {heading}") + 2          # past the blank line
    rows = []
    for line in lines[start:]:
        if not line.startswith("|"):
            break
        rows.append(line)
    return rows


def cost_fixture(r) -> None:
    r.write_json(".claude-plugin/marketplace.json", {"plugins": [
        {"name": "a", "source": "./plugins/a", "description": "A"},
        {"name": "b", "source": "./plugins/b", "description": "B"},
        {"name": "c", "source": "./plugins/c", "description": "C (in no profile)"},
        {"name": "up", "source": {"source": "url", "url": "https://example.invalid/up.git", "sha": "0" * 40},
         "description": "External"}]})
    r.write("plugins/a/skills/s1/SKILL.md", "---\nname: s1\ndescription: Does one thing.\n---\n")
    r.write("plugins/a/skills/s2/SKILL.md", "---\nname: s2\ndescription: Does another thing.\n---\n")
    r.write("plugins/a/skills/hidden/SKILL.md",
            "---\nname: hidden\ndescription: Never listed.\ndisable-model-invocation: true\n---\n")
    r.write("plugins/b/commands/go.md", "---\ndescription: Goes.\n---\n")
    r.write("plugins/c/skills/s3/SKILL.md", "---\nname: s3\ndescription: Third.\n---\n")
    r.write_json("profiles.json", {"profiles": {"one": ["a", "up"], "two": ["b", "ghost"]}, "copilotDefault": ["one"],
                                   "listingBudget": {"$comment": "x",
                                                     "first": {"label": "First CLI", "chars": 100, "profiles": ["one"]},
                                                     "second": {"chars": 30, "profiles": ["one", "two"]}}})


def test_cost_tables_show_profiles_budgets_and_what_is_not_measured(bare_layout):
    cost_fixture(bare_layout)
    bare_layout.gen_catalog()
    text = bare_layout.read("SKILLS.md")
    a = cost("a", "s1", "Does one thing.") + cost("a", "s2", "Does another thing.")
    a_names = floor("a", "s1") + floor("a", "s2")
    b, b_names = cost("b", "go", "Goes."), floor("b", "go")
    c, c_names = cost("c", "s3", "Third."), floor("c", "s3")
    assert text.startswith("# Skills catalog\n\nGenerated by `scripts/gen-catalog.py` on every sync — do not edit by hand.\n\n"
                           f"## Listing cost\n\n{INTRO}\n\n### Per profile\n\n")
    assert cost_rows(text, "Per profile") == [
        "| Profile | Plugins | Entries | Characters | Names only | First CLI budget | second budget |",
        "|---|---|---|---|---|---|---|",
        f"| `one` | 2 | 2 | {a:,} | {a_names:,} | {round(100 * a / 100)}% of 100 | {round(100 * a / 30)}% of 30 |",
        f"| `two` | 1 | 1 | {b:,} | {b_names:,} | – | {round(100 * b / 30)}% of 30 |",   # "ghost" is no marketplace plugin
        f"| all plugins | 4 | 4 | {a + b + c:,} | {a_names + b_names + c_names:,} | – | – |",   # also `c`, in no profile
    ]
    assert "\nNot measured: `up` (referenced from upstream, its skills are not in this repo).\n" in text
    assert cost_rows(text, "Per plugin") == [
        "| Plugin | Profile | Skills | Commands | Characters | Names only |", "|---|---|---|---|---|---|",
        f"| `a` | one | 2 | 0 | {a:,} | {a_names:,} |",       # the hidden skill is not listed, so it costs nothing
        f"| `c` | – | 1 | 0 | {c:,} | {c_names:,} |",       # most characters first
        f"| `b` | two | 0 | 1 | {b:,} | {b_names:,} |",
        "| `up` | one | – | – | not measured | – |",
    ]


def test_plugins_with_equal_costs_are_sorted_by_name_not_by_marketplace_order(bare_layout):
    r = bare_layout
    r.write_json(".claude-plugin/marketplace.json", {"plugins": [
        {"name": name, "source": f"./plugins/{name}", "description": name} for name in ("pc", "pa", "pb")]})
    for name in ("pc", "pa", "pb"):
        r.write(f"plugins/{name}/skills/s/SKILL.md", "---\nname: s\ndescription: Does it.\n---\n")
    r.gen_catalog()
    rows = cost_rows(r.read("SKILLS.md"), "Per plugin")[2:]
    assert [row.split("|")[1].strip() for row in rows] == ["`pa`", "`pb`", "`pc`"]
    assert len({row.split("|")[5] for row in rows}) == 1     # the same Characters cell: only the name orders them


