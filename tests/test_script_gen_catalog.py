INTRO = ("Claude Code puts one line per skill and command (`- plugin:name: description`) into the model's context in "
         "every session. These tables count those characters, including the line break after each entry "
         "(`README.md`, \"Listing budget\"). Copilot CLI is assumed to list the same way: its format and what it does "
         "over its budget are not verified, so its column uses the same count. Skills with "
         "`disable-model-invocation: true` are not listed and agents are not part of it. \"Names only\" is what "
         "stays when a client drops every description.")


def cost(plugin: str, name: str, text: str) -> int:
    """One listing entry: "- plugin:name: text" and a line break."""
    return len(f"{plugin}:{name}") + 5 + len(text)


def floor(plugin: str, name: str) -> int:
    """The same entry without its description: "- plugin:name" and a line break."""
    return len(f"{plugin}:{name}") + 3


def expected_costs() -> str:
    alpha = [("a-quoted", "Quoted: keeps the colon."), ("b-folded", "Folded description over two lines."),
             ("c-long", LONG), ("d-literal", "Literal block, joined too."), ("e-no-frontmatter", ""),
             ("run", "Runs alpha."), ("deep", "A nested command.")]
    a_chars = sum(cost("alpha", n, t) for n, t in alpha)
    a_names = sum(floor("alpha", n) for n, _ in alpha)
    b_chars, b_names = cost("beta", "listed", "Listed."), floor("beta", "listed")
    g_chars = cost("gamma", "one", "One.") + cost("gamma", "two", "Two.")
    g_names = floor("gamma", "one") + floor("gamma", "two")
    rows = sorted([("alpha", 5, 2, a_chars, a_names), ("beta", 1, 0, b_chars, b_names), ("gamma", 2, 0, g_chars, g_names),
                   ("empty", 0, 0, 0, 0)], key=lambda r: (-r[3], r[0]))
    table = "".join(f"| `{n}` | – | {sk} | {cm} | {c:,} | {f:,} |\n" for n, sk, cm, c, f in rows)
    return (f"## Listing cost\n\n{INTRO}\n\n### Per plugin\n\n"
            "| Plugin | Profile | Skills | Commands | Characters | Names only |\n|---|---|---|---|---|---|\n"
            f"{table}| `ext` | – | – | – | not measured | – |\n| `gh` | – | – | – | not measured | – |\n\n")


def expected_cut() -> str:
    """first_sentence(): whitespace collapsed, cut at the last space within 220 characters, plus an ellipsis."""
    cut = LONG[:220]
    return cut[: cut.rfind(" ")] + "…"


def test_catalog_matches_the_expected_markdown(bare_layout):
    build(bare_layout)
    res = bare_layout.gen_catalog()
    assert res.stdout == "==> wrote SKILLS.md (6 plugins)\n"
    assert bare_layout.read("SKILLS.md") == EXPECTED.replace("CUT", expected_cut()).replace("COSTS", expected_costs())


def test_long_description_is_cut_at_a_word_boundary(bare_layout):
    build(bare_layout)
    bare_layout.gen_catalog()
    row = next(x for x in bare_layout.read("SKILLS.md").splitlines() if "c-long" in x)
    text = row.split(" | ", 1)[1].removesuffix(" |")
    assert len(LONG) > 220
    assert text.endswith("…") and len(text) <= 221
    assert LONG.startswith(text[:-1]) and LONG[len(text) - 1] == " "


def test_output_is_deterministic(bare_layout):
    build(bare_layout)
    bare_layout.gen_catalog()
    first = bare_layout.path("SKILLS.md").read_bytes()
    bare_layout.gen_catalog()
    assert bare_layout.path("SKILLS.md").read_bytes() == first
    assert first.endswith(b"\n") and not first.endswith(b"\n\n")


